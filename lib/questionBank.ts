/** 从指定套件题库中随机抽取并打乱顺序，构建一次测评的题目 */
export function buildAssessment(
  trackId: TrackId,
  count: number = QUESTIONS_PER_ASSESSMENT
): Question[] {
  const pool = QUESTION_POOL[trackId] ?? [];
  const sampled = shuffle(pool).slice(0, Math.min(count, pool.length));
  return sampled.map((question) => ({
    ...question,
    options: shuffle(question.options),
  }));
}



