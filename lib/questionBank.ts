/** Fisher–Yates 洗牌，返回新数组 */
export function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * 构造一道迫选题：
 * 6 个选项按「套件维度顺序」传入，与 TRACKS[trackId].dimensions 严格一一对应。
 * 运行时会对选项与题目进行随机打乱，确保不同候选人的题目不完全相同。
 */
function q(
  trackId: TrackId,
  id: string,
  scenario: string,
  optionTexts: string[]
): Question {
  const dims = TRACKS[trackId].dimensions;
  const options: Option[] = dims.map((dimKey, i) => ({
    id: `${id}-opt-${i + 1}`,
    dimensionKey: dimKey,
    text: optionTexts[i],
  }));
  return { id, trackId, scenario, options };
}

